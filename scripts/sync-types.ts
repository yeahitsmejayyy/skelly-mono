// Emits the server's AppRouter contract and copies it into each frontend as src/lib/app-router.d.ts.
// Run after changing any procedure, then commit the copies. The frontends never import server
// source, so they typecheck and build without Bun types.
import { $ } from "bun";
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";

// scripts/mount.ts rewrites these two lines when it mounts containers. Do not reformat them.
const BACKEND = "apps/server";
const CONTRACT_TARGETS: string[] = [];

const root = resolve(import.meta.dir, "..");
const backend = resolve(root, BACKEND);

if (!existsSync(resolve(backend, "package.json"))) {
  console.error(`✖ no backend at ${BACKEND}`);
  process.exit(1);
}
if (CONTRACT_TARGETS.length === 0) {
  console.log("No frontends consume the contract. Nothing to sync.");
  process.exit(0);
}

await $`bun run types:emit`.cwd(backend).quiet();
const contract = readFileSync(resolve(backend, "dist/types/appRouter.d.ts"), "utf8");
const header =
  `// Generated by \`bun run sync:types\` from ${BACKEND}/src/appRouter.ts. Do not edit.\n` +
  "// When a procedure changes, run the sync again and commit the result.\n\n";

for (const app of CONTRACT_TARGETS) {
  writeFileSync(resolve(root, `apps/${app}/src/lib/app-router.d.ts`), header + contract);
  console.log(`✔ apps/${app}/src/lib/app-router.d.ts`);
}
